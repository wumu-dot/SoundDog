import numpy as np, sys
sys.path.insert(0, 'scripts')
from gen_dct_table import dct_matrix, NB_DCT_OUT, NB_MEL
M = dct_matrix(NB_DCT_OUT, NB_MEL)

def ref(mel):
    x = np.array(mel, dtype=float)
    vmax = x.max()
    x = x / vmax if vmax > 1e-12 else x.copy()
    return M @ np.log(x + 1e-6) * 100

cases = [
 ('quiet f=98',
  [141,217,140,254,199,235,189,178,216,358,205,264,320,322,336,363,381,270,473,442,470,643,841,995,683,596,412,513,514,674,484,588],
  [-823,-254,-36,37,-42,7,24,-58,11,-4,-34,12,-19]),
 ('1kHz f=903',
  [227,172,299,274,340,449,4154,45760,9552,405,406,310,376,254,255,383,386,428,586,576,767,753,527,494,599,644,697,644,500,559,572,471],
  [-3480,34,4,-135,-324,-264,-64,132,175,182,85,-71,-127]),
 ('blow f=1808',
  [202787,321698,90091,197610,143241,148798,226967,347540,426894,349163,286199,461968,581577,405413,536012,582860,614001,966536,646464,843405,918619,814938,1122566,1447535,1440049,759477,638853,748475,764828,617258,625209,893759],
  [-860,-318,-135,35,-32,20,48,11,70,6,13,23,-31]),
]
for name, mel, fw in cases:
    pc = ref(mel)
    d = np.abs(pc - np.array(fw)).max()
    verdict = 'PASS' if d <= 6 else 'FAIL'
    print('%s: max|diff| = %.1f -> %s' % (name, d, verdict))

