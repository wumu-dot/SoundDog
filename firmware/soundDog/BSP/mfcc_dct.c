/* 编译期耦合检查（评审 M-2 惯例：A3-02 改 Mel 维度时即刻暴露） */
_Static_assert(MFCC_DCT_IN == MEL_NB_BANDS,
               "mfcc_dct input must equal mel band count");

/* log 域中间缓冲（非重入来源；仅 specTask 单消费者） */
static float32_t s_logmel[MFCC_DCT_IN];

/* ---- 接口实现 ---- */

int mfcc_dct_process(const float32_t *mel32, float32_t *mfcc13)
{
  if ((mel32 == NULL) || (mfcc13 == NULL)) { return -1; }

  /* ① absmax 归一化（音量鲁棒；Mel 能量为幅度谱口径恒 ≥0）
   * 坑 2 防护：max ≤ 1e-12（静音帧全 0）跳过归一化直接走 +1e-6 地板，
   * 输出确定值（c0=-11000 常数行、其余≈0）而非 NaN。 */
  float32_t vmax = 0.0f;
  for (uint32_t i = 0u; i < MFCC_DCT_IN; i++) {
    if (mel32[i] > vmax) { vmax = mel32[i]; }
  }
  if (vmax > 1.0e-12f) {
    for (uint32_t i = 0u; i < MFCC_DCT_IN; i++) {
      s_logmel[i] = mel32[i] / vmax;
    }
  } else {
    for (uint32_t i = 0u; i < MFCC_DCT_IN; i++) {
      s_logmel[i] = mel32[i];
    }
  }

  /* ② +1e-6 偏移（官方 L134 字面值）→ ln（官方 L135 口径）。
   * 两 API 文件在 vendored 树（FastMath/BasicMath），Makefile 已登记。 */
  arm_offset_f32(s_logmel, 1.0e-6f, s_logmel, MFCC_DCT_IN);
  arm_vlog_f32(s_logmel, s_logmel, MFCC_DCT_IN);

  /* ③ 13×32 矩阵乘（行主序 416 MAC，自写循环——对策 B） */
  for (uint32_t k = 0u; k < MFCC_DCT_OUT; k++) {
    float32_t acc = 0.0f;
    const float32_t *row = &s_dct_coefs[k * MFCC_DCT_IN];
    for (uint32_t j = 0u; j < MFCC_DCT_IN; j++) {
      acc += row[j] * s_logmel[j];
    }
    mfcc13[k] = acc;
  }

  return 0;
}
