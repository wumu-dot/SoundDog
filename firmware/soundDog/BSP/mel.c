/* ==== 内部状态（全静态：大数组不上任务栈——ST 社区 hardfault 头号原因） ==== */

/* 独立 512 点实例：fft.c 是 256 点且 fft_run 单消费者（设计 §1.5 决策）。
 * f32 rfft 无全局状态（状态全在实例结构体内），与 fft.c 互不污染。 */
static arm_rfft_fast_instance_f32 s_rfft;

static float32_t s_in[MEL_FFT_LEN];              /* 512：400 样 + 112 零 */
static float32_t s_tmp[MEL_FFT_LEN + 2u];        /* rfft 输出 + Nyquist 解包位（514） */
static float32_t s_mag[(MEL_FFT_LEN / 2u) + 1u]; /* 257 幅度谱（坑 2：+1 含 Nyquist） */

static uint8_t s_inited = 0u;

int mel_init(void)
{
  if (s_inited != 0u) { return 0; }                    /* 幂等 */
  arm_status st = arm_rfft_fast_init_f32(&s_rfft, MEL_FFT_LEN);
  if (st != ARM_MATH_SUCCESS) { return -1; }
  s_inited = 1u;
  return 0;
}

int mel_process(const float32_t *frame400, float32_t *mel_out)
{
  if ((frame400 == NULL) || (mel_out == NULL) || (s_inited == 0u)) {
    return -1;
  }

  /* 坑 7：立即拷贝（mfcc_last_frame 返回静态缓冲，下一次 mfcc_feed 覆写） */
  memcpy(s_in, frame400, (size_t)MEL_FRAME_IN * sizeof(float32_t));
  memset(&s_in[MEL_FRAME_IN], 0,
         (size_t)(MEL_FFT_LEN - MEL_FRAME_IN) * sizeof(float32_t));

  arm_rfft_fast_f32(&s_rfft, s_in, s_tmp, 0u);

  /* 坑 1：rfft 打包格式解包——照抄官方 arm_mfcc_f32（v1.14.4 L113-115）。
   * 打包输出：[0]=DC, [1]=Nyquist, [2k]/[2k+1]=bin k 的 re/im；
   * 解包为 257 个复数排布：Nyquist 搬至 [fftLen]（bin 256 实部位），
   * [1]（DC 虚部位）清零。不做此步 → bin1/Nyquist 错 → 低频带与带 31 静默数值错。 */
  s_tmp[MEL_FFT_LEN]        = s_tmp[1];
  s_tmp[MEL_FFT_LEN + 1u]   = 0.0f;
  s_tmp[1]                  = 0.0f;

  /* 幅度谱口径（官方 #279/#338 印证）：257 点，显式 +1 防按 256 写漏 Nyquist */
  arm_cmplx_mag_f32(s_tmp, s_mag, (MEL_FFT_LEN / 2u) + 1u);

  /* 稀疏三角滤波：与官方 arm_mfcc_f32 L120-131 同构（off 累加） */
  uint32_t off = 0u;
  for (uint32_t i = 0u; i < MEL_NB_BANDS; i++) {
    arm_dot_prod_f32(&s_mag[mel_filt_pos[i]], &mel_coefs[off],
                     (uint32_t)mel_filt_len[i], &mel_out[i]);
    off += mel_filt_len[i];
  }
  return 0;
}
